"""
Dataset loader for cograph (join/union) datasets.

Loads pre-generated .pt files (lists of adjacency matrices) from
data/cograph_dense/ and data/cograph_sparse/.
Modeled on spectre_dataset.py for unattributed graphs.
"""

import os
import pathlib

import torch
import torch_geometric.utils
from torch_geometric.data import InMemoryDataset

from datasets.abstract_dataset import AbstractDataModule, AbstractDatasetInfos


class CographDataset(InMemoryDataset):
    """Loads pre-split .pt files containing lists of adjacency matrices."""

    def __init__(
        self,
        dataset_name,
        split,
        root,
        transform=None,
        pre_transform=None,
        pre_filter=None,
    ):
        self.dataset_name = dataset_name
        self.split = split
        super().__init__(root, transform, pre_transform, pre_filter)
        self.data, self.slices = torch.load(self.processed_paths[0])
        self.num_graphs = len(self.data.n_nodes)

    @property
    def raw_file_names(self):
        return ["train.pt", "val.pt", "test.pt"]

    @property
    def processed_file_names(self):
        return [self.split + ".pt"]

    def download(self):
        """
        No download needed — .pt files are pre-generated by our data pipeline.
        Copy them from the project data/ directory into the raw/ directory.
        """
        source_dir = pathlib.Path(__file__).parents[4] / "data" / self.dataset_name
        for fname in self.raw_file_names:
            shutil.copy2(source_dir / fname, os.path.join(self.raw_dir, fname))


    def process(self):
        """Convert raw adjacency lists to PyG InMemoryDataset format."""
        file_idx = {"train": 0, "val": 1, "test": 2}
        raw_dataset = torch.load(self.raw_paths[file_idx[self.split]])

        data_list = []
        for adj in raw_dataset:
            n = adj.shape[-1]
            X = torch.ones(n, 1, dtype=torch.float)
            y = torch.zeros([1, 0]).float()
            edge_index, _ = torch_geometric.utils.dense_to_sparse(adj)
            edge_attr = torch.zeros(edge_index.shape[-1], 2, dtype=torch.float)
            edge_attr[:, 1] = 1
            num_nodes = n * torch.ones(1, dtype=torch.long)
            data = torch_geometric.data.Data(
                x=X, edge_index=edge_index, edge_attr=edge_attr, y=y, n_nodes=num_nodes
            )

            if self.pre_filter is not None and not self.pre_filter(data):
                continue
            if self.pre_transform is not None:
                data = self.pre_transform(data)

            data_list.append(data)

        torch.save(self.collate(data_list), self.processed_paths[0])


class CographDataModule(AbstractDataModule):
    def __init__(self, cfg):
        self.cfg = cfg
        self.datadir = cfg.dataset.datadir
        base_path = pathlib.Path(os.path.realpath(__file__)).parents[2]
        root_path = os.path.join(base_path, self.datadir)

        datasets = {
            "train": CographDataset(
                dataset_name=self.cfg.dataset.name, split="train", root=root_path
            ),
            "val": CographDataset(
                dataset_name=self.cfg.dataset.name, split="val", root=root_path
            ),
            "test": CographDataset(
                dataset_name=self.cfg.dataset.name, split="test", root=root_path
            ),
        }

        train_len = len(datasets["train"].data.n_nodes)
        val_len = len(datasets["val"].data.n_nodes)
        test_len = len(datasets["test"].data.n_nodes)
        print(f"Dataset sizes: train {train_len}, val {val_len}, test {test_len}")

        super().__init__(cfg, datasets)
        self.inner = self.train_dataset

    def __getitem__(self, item):
        return self.inner[item]


